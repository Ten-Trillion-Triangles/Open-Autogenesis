// Generate `LiveMode.kt` from the `kvision.liveMode` Gradle property. Putting
// the value in a real Kotlin file (rather than a `-Xdefine=...` free compiler
// arg) is portable across Kotlin/JS compiler versions and is visible to the
// IDE / ktlint / ksp.
val liveModeGeneratedDir: java.io.File = layout.buildDirectory.dir("generated/liveMode").get().asFile
val generateLiveMode by tasks.registering {
    group = "build"
    description = "Generates LiveMode.kt from the kvision.liveMode Gradle property."
    outputs.dir(liveModeGeneratedDir)
    inputs.property("kvisionLiveMode", kvisionLiveMode)
    doLast {
        liveModeGeneratedDir.mkdirs()
        val file = File(liveModeGeneratedDir, "LiveMode.kt")
        file.writeText(
            """// Auto-generated by kvisionApp/build.gradle.kts — do not edit by hand.
package globals

/** Build-time mirror of the kvisionApp `kvision.liveMode` Gradle property. */
object LiveMode {
    const val liveMode: Boolean = ${kvisionLiveMode}
}
"""
        )
    }
}

