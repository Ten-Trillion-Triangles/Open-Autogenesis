// The Kotlin/JS multiplatform plugin only copies resources from the
// declaring module's own source sets into jsProcessResources output;
// resources declared on a *dependency* module (e.g. the sharedModel
// commonMain resources) are NOT merged into the consuming module's
// processedResources tree. `MenuMusicPlayer` fetches
// `audio/audio-tracks.json` from the dev server's public path, which
// is rooted at `kvisionApp/build/processedResources/js/main`, so we
// have to physically copy the JSON in via a small sync task. The file
// itself is the designer's authoritative catalog (server's
// `MusicSelector` reads the same file via classpath), so the source
// of truth is the sharedModel module — this task mirrors it into the
// kvisionApp's processed resources before they are served.
val syncSharedAudioTracks by tasks.registering(Copy::class) {
    group = "build"
    description = "Copies sharedModel's commonMain audio-tracks.json into kvisionApp's processedResources/js/main/audio/."
    from(rootProject.file("sharedModel/src/commonMain/resources/audio/audio-tracks.json"))
    into(layout.buildDirectory.dir("processedResources/js/main/audio"))
    inputs.file(rootProject.file("sharedModel/src/commonMain/resources/audio/audio-tracks.json"))
    outputs.file(layout.buildDirectory.file("processedResources/js/main/audio/audio-tracks.json"))
}

tasks.named("jsProcessResources") {
    dependsOn(syncSharedAudioTracks)
}

