// Generate a VAPID P-256 ECDSA keypair for Web Push notifications.
// The private key is written to ~/.autogenesis/vapid_private.pem (created on
// first run, never regenerated thereafter). The public key is extracted and
// Base64URL-encoded into build/generated/vapid/vapid_public.json so the
// Kotlin/JS PushNotificationService can fetch it as the
// `applicationServerKey` argument to `pushManager.subscribe()`.
val vapidDir: java.io.File = layout.buildDirectory.dir("generated/vapid").get().asFile
val generateVapidKeys by tasks.registering {
    group = "build"
    description = "Generates VAPID P-256 ECDSA keypair at ~/.autogenesis/vapid_private.pem and writes the Base64URL-encoded public key into build/generated/vapid/vapid_public.json."
    outputs.dir(vapidDir)
    doLast {
        vapidDir.mkdirs()
        val homeDir = System.getProperty("user.home") ?: System.getenv("HOME") ?: "/root"
        val privateKeyFile = File(File(homeDir, ".autogenesis"), "vapid_private.pem")
        if (!privateKeyFile.exists()) {
            privateKeyFile.parentFile.mkdirs()
            val genProcess = ProcessBuilder(
                "openssl", "ecparam", "-name", "prime256v1", "-genkey", "-noout",
                "-out", privateKeyFile.absolutePath
            ).redirectErrorStream(true).start()
            val genExit = genProcess.waitFor()
            val genOutput = genProcess.inputStream.bufferedReader().readText()
            check(genExit == 0) { "openssl ecparam failed (exit=$genExit): $genOutput" }
            logger.warn("Generated VAPID private key at ${privateKeyFile.absolutePath}")
        }
        // Extract the public key as DER (SubjectPublicKeyInfo, X.509), then
        // strip the SEQUENCE/OID headers and BIT STRING tag+length to get the
        // raw 65-byte uncompressed point (0x04 || X || Y), then Base64URL-encode
        // it (no padding) for the applicationServerKey parameter.
        val derProcess = ProcessBuilder(
            "openssl", "ec", "-in", privateKeyFile.absolutePath, "-pubout",
            "-outform", "DER"
        ).redirectErrorStream(true).start()
        val derBytes = derProcess.inputStream.readBytes()
        val derExit = derProcess.waitFor()
        val derOutput = String(derBytes)
        check(derExit == 0) { "openssl ec -pubout failed: $derOutput" }
        val rawPoint = derBytes.copyOfRange(derBytes.size - 65, derBytes.size)
        val encoder = Base64.getUrlEncoder().withoutPadding()
        val base64Url = encoder.encodeToString(rawPoint)
        val outFile = File(vapidDir, "vapid_public.json")
        outFile.writeText("""{"applicationServerKey":"$base64Url"}""")
        logger.lifecycle("VAPID public key written to ${outFile.absolutePath} (${base64Url.length} chars)")
    }
}

