/**
 * Rolls availability for each criterion independently. Each criterion's chancePercent
 * determines whether it appears in the eligible pool for this turn.
 *
 * @param criteria The full list of criteria with their chancePercent values.
 * @return Criteria that passed their availability roll. Guaranteed non-empty (falls back to all criteria).
 */
// [APEX-INJECTED-DEBUG-20260530] Added per-criterion roll logging for traceability
fun rollCriteriaAvailability(criteria: List<InjectableCriterion>): List<InjectableCriterion>
{
    if(criteria.isEmpty()) return emptyList()

    val rollResults = criteria.map { criterion ->
        val roll = kotlin.random.Random.nextInt(0, 101)
        val passed = roll < criterion.chancePercent
        RollResult(criterion, roll, passed)
    }

    // Log each criterion's roll result
    val rollResultsStr = rollResults.joinToString("; ") { r ->
        val status = if(r.passed) "✅ PASS" else "❌ FAIL"
        "[${r.criterion.id}] ${r.criterion.description.take(25)}: roll=${r.roll} chg=${r.criterion.chancePercent} $status"
    }
    Logger.debug(LogCategory.LLM, "Criteria roll: $rollResultsStr")

    val passed = rollResults.filter { it.passed }.map { it.criterion }
    return passed.ifEmpty {
        Logger.debug(LogCategory.LLM, "Criteria roll: all failed — no criteria fire this turn (default is grounded geopolitical reality)")
        emptyList()
    }
}

private data class RollResult(
    val criterion: InjectableCriterion,
    val roll: Int,
    val passed: Boolean
)

/**
 * Builds the numbered criteria list string for the guide pipe footer.
 * Rolls each criterion's availability and formats the result as a numbered list.
 *
 * @param criteria The full list of criteria to roll and format.
 * @return Numbered list string, e.g. "1. Kafka-esque...\n2. Keillor-esque..."
 */
fun buildCriteriaListForGuide(criteria: List<InjectableCriterion>): String
{
    val eligible = rollCriteriaAvailability(criteria)
    return eligible.mapIndexed { index, criterion ->
        "${index + 1}. ${criterion.description}"
    }.joinToString("\n")
}

/**
 * Chooses one of four strategies and emits the numbered Step 2 instructions.
 *
 * @param promptSeed Optional user prompt seed to deterministically drive randomness.
 * @param strategy The selection strategy to use.
 * @param criteria The injectable criteria list to select from.
 * @return A newline-separated list of unique criteria (numbered and annotated with their original indices).
 */
private fun buildStepTwoInstructions(promptSeed: String?, strategy: WriterSelectionStrategy, criteria: List<InjectableCriterion>): String
{
    val random = kotlin.random.Random(deriveSeedFromPrompt(promptSeed))

    Logger.debug(LogCategory.LLM, "Selecting writing strategy: $strategy")

    // Roll availability for each criterion first
    val eligibleCriteria = rollCriteriaAvailability(criteria)

    val selectedCriteria = when(strategy)
    {
        WriterSelectionStrategy.RANDOM ->
        {
            val alternatives = listOf(
                WriterSelectionStrategy.GEOPOLITICS_ONLY,
                WriterSelectionStrategy.RANDOM_UP_TO_FIVE,
                WriterSelectionStrategy.WEIGHTED,
                WriterSelectionStrategy.ORIGINAL
            )
            val chosen = alternatives[random.nextInt(alternatives.size)]
            Logger.debug(LogCategory.LLM, "RANDOM strategy selected sub-strategy: $chosen")
            return@buildStepTwoInstructions buildStepTwoInstructions(promptSeed, chosen, criteria)
        }
        WriterSelectionStrategy.GEOPOLITICS_ONLY -> eligibleCriteria.filter { it.id == 4 }
        WriterSelectionStrategy.RANDOM_UP_TO_FIVE -> selectRandomUpToFiveCriteria(eligibleCriteria, random)
        WriterSelectionStrategy.WEIGHTED ->
        {
            val geopolitics = eligibleCriteria.find { it.id == 4 }
            val rabellesian = eligibleCriteria.find { it.id == 7 }
            val reallyDumb = eligibleCriteria.find { it.id == 10 }
            val base = listOfNotNull(geopolitics, rabellesian, reallyDumb)
            val extra = (eligibleCriteria - base.toSet()).shuffled(random).take(3)
            base + extra
        }
        WriterSelectionStrategy.ORIGINAL -> eligibleCriteria
    }

    Logger.debug(LogCategory.LLM, "Selecting writing criteria: $selectedCriteria")

    return selectedCriteria.mapIndexed { index, criterion ->
        "${index + 1}. [${criterion.id}] ${criterion.description}"
    }.joinToString("\n")
}

internal fun selectRandomUpToFiveCriteria(eligibleCriteria: List<InjectableCriterion>, random: kotlin.random.Random): List<InjectableCriterion>
{
    if(eligibleCriteria.isEmpty()) return emptyList()

    val selectionCount = random.nextInt(1, minOf(eligibleCriteria.size, 5) + 1)
    return eligibleCriteria.shuffled(random).take(selectionCount)
}

/**
 * Derives a deterministic numeric seed from the user prompt for `Random(seed)`.
 *
 * @param prompt The raw user prompt.
 * @return A stable long hash value (0 when the prompt is blank).
 */
private fun deriveSeedFromPrompt(prompt: String?): Long
{
    if(prompt.isNullOrEmpty())
    {
        return 0L
    }

    var hash = 0L
    for(char in prompt)
    {
        hash = hash * 31 + char.code
    }
    return hash
}

