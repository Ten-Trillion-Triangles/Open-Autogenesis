/**
 * Rolls each rule category independently and selects weighted random rules from firing categories.
 * Multiple categories can fire per turn, in which case all applicable rules are concatenated.
 *
 * @param ruleCategories The categories to roll against.
 * @return A string combining all selected rule descriptions, or empty string if no category fired.
 */
fun selectRulesFromCategories(ruleCategories: List<RuleCategory>): String
{
    if(ruleCategories.isEmpty()) return ""

    val firedRules = mutableListOf<String>()

    for(category in ruleCategories)
    {
        val roll = kotlin.random.Random.nextInt(0, 101)
        // Use `<=` (not `<`) so a `chancePercent` of 100 actually fires 100% of
        // the time. `nextInt(0, 101)` returns a value in [0, 100] inclusive;
        // `< chancePercent` would let roll == 100 miss at chancePercent == 100
        // (≈1 % per roll, ≈18 % over a 20-iteration loop). `SelectRulesFromCategoriesTest.single100PercentCategoryFiresAndReturnsRule`
        // exercises this exact boundary.
        val fired = roll <= category.chancePercent
        Logger.debug(LogCategory.LLM, "RuleCategory roll: ${category.name}: roll=$roll chance=${category.chancePercent} ${if(fired) "✅ FIRED" else "❌ miss"}")
        if(fired)
        {
            if(category.rules.isNotEmpty())
            {
                val totalWeight = category.rules.sumOf { it.weight.coerceAtLeast(1) }
                var pick = kotlin.random.Random.nextInt(0, totalWeight)
                for(rule in category.rules)
                {
                    pick -= rule.weight.coerceAtLeast(1)
                    if(pick < 0)
                    {
                        Logger.debug(LogCategory.LLM, "Rule category '${category.name}' fired, selected rule: ${rule.id}")
                        firedRules.add(rule.description)
                        break
                    }
                }
            }
        }
    }

    if(firedRules.isEmpty())
    {
        return ""
    }

    val result = firedRules.joinToString("\n\n")
    Logger.debug(LogCategory.LLM, "Selected rules: $result")
    return result
}

