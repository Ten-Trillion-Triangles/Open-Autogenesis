/**
 * Generated input class for the guide pipe. This is generated by the pre-init function and replaces the
 * text input of the player action coming in from the system.
 *
 * @param playerData Serialized string of either [structs.Player] or [structs.Npc]. This is pulled in
 * from the builder function, serialized and saved into the pipeline's mini-bank. The value is then
 * extracted back at pre-init time.
 * @param playerAction The action the player is attempting to make. Formatted into 3rd person by a prior
 * pipe before we have arrived here.
 * @param weights Affects how the guide pipe needs to account for deciding the possible outcomes for the
